// ✅ ОБЩИЙ ХЕЛПЕР ГОМОГЛИФОВ + ПЕРЕКЛЮЧАТЕЛЬ «Кир→Лат»
// ============================================================
// Проблема: данные в БД часто набраны «смешанным алфавитом» —
// «ШBEЛЛЕР» (B, E, P — латиница), «BЫTAЛKИBATEЛЬ», «CTOЙKA» и т.п.
// Поиск чистой кириллицей такие строки не находил.
//
// Решение: буквы-двойники считаются одним и тем же символом:
//   А=A, В=B, С=C, Е=E, Н=H, К=K, М=M, О=O, Р=P, Т=T, Х=X, У=Y
//   (+ ё=е — стандартная русская нормализация поиска).
//
// Режим переключается флажком «Кир→Лат» в панели фильтров (план
// производства) и хранится в localStorage (ключ 'homoglyphSearch').
// По умолчанию ВКЛЮЧЁН: гомоглиф-поиск — надмножество точного,
// он не скрывает результаты, а только добавляет совпадения.
//
// Кто использует этот хелпер:
//   * filterable-table.js — добавляет hg=0 к запросам таблиц, когда режим
//     выключен (сервер сравнивает буквально);
//   * virtual-select.js — то же для поисковых запросов выпадающих списков;
//   * app-route-editor.js / modules/transportTypes.js — клиентские
//     фильтры через matches();
//   * сервер (src/routes/helpers/homoglyphs.js) — GLOB-классы и JS-фильтры.
//
// Серверная копия (CJS): src/routes/helpers/homoglyphs.js —
// ПРИ ИЗМЕНЕНИИ КАРТЫ ПРАВИТЬ ОБА ФАЙЛА.
// ============================================================

export const STORAGE_KEY = 'homoglyphSearch'; // localStorage: '1'/'0'

// Кириллица -> латиница (буквы-двойники) + ё->е
const CYR2LAT = {
  'а': 'a', 'в': 'b', 'с': 'c', 'е': 'e', 'н': 'h', 'к': 'k',
  'м': 'm', 'о': 'o', 'р': 'p', 'т': 't', 'х': 'x', 'у': 'y',
  'ё': 'e',
  'А': 'A', 'В': 'B', 'С': 'C', 'Е': 'E', 'Н': 'H', 'К': 'K',
  'М': 'M', 'О': 'O', 'Р': 'P', 'Т': 'T', 'Х': 'X', 'У': 'Y',
  'Ё': 'E',
};

// Заменить кириллические буквы-двойники на латиницу (А->A, В->B, Р->P, ...)
export function toLatin(str) {
  return String(str ?? '').replace(/./gu, (ch) => CYR2LAT[ch] || ch);
}

// Каноническая форма: lower + ё->е + кириллица->латиница.
// Символы без двойников (ш, л, Щ, Д...) остаются как есть —
// в данных и в запросе они записаны одинаково.
export function normalize(str) {
  return toLatin(String(str ?? '').toLowerCase());
}

// Включён ли режим «Кир→Лат» (по умолчанию — да)
export function isEnabled() {
  try {
    return localStorage.getItem(STORAGE_KEY) !== '0';
  } catch {
    return true;
  }
}

// Сохранить состояние переключателя
export function setEnabled(v) {
  try {
    localStorage.setItem(STORAGE_KEY, v ? '1' : '0');
  } catch {
    /* localStorage недоступен — режим не сохраняется, но работает */
  }
}

// Сравнение «содержит» с учётом переключателя:
//   включён  -> обе стороны нормализуются (гомоглифы равны);
//   выключен -> обычное сравнение в нижнем регистре.
export function matches(haystack, needle) {
  const raw = String(haystack ?? '').toLowerCase();
  const n = String(needle ?? '').toLowerCase();
  if (!n) return true;
  return isEnabled() ? normalize(raw).includes(normalize(n)) : raw.includes(n);
}
